#!/usr/bin/env node
'use strict';

// Writes a plain-HTML summary of the dataset into index.html (between the static-summary markers) and
// refreshes the link-preview description. It is what no-JavaScript readers, crawlers and link previews see;
// the app replaces it on load. Every figure comes from data/gcc-yemen-summary.json and the full records.
const fs = require('node:fs');
const path = require('node:path');

const root = path.resolve(__dirname, '..');
const summary = JSON.parse(fs.readFileSync(path.join(root, 'data/gcc-yemen-summary.json'), 'utf8'));
const full = JSON.parse(fs.readFileSync(path.join(root, 'data/gcc-yemen-measures.json'), 'utf8'));
const escape = (value) => String(value ?? '').replace(/[&<>"']/g, (char) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' })[char]);
const date = (iso) => new Date(`${iso}T00:00:00Z`).toLocaleDateString('en-GB', { day: 'numeric', month: 'long', year: 'numeric', timeZone: 'UTC' });
const countries = ['Bahrain', 'Kuwait', 'Oman', 'Qatar', 'Saudi Arabia', 'United Arab Emirates', 'Yemen'];
const counts = Object.fromEntries(countries.map((country) => [country, full.records.filter((record) => record.country === country).length]));
const first = full.records.map((record) => record.date).filter(Boolean).sort()[0];
const latest = full.records.filter((record) => record.date).sort((a, b) => b.date.localeCompare(a.date) || a.country.localeCompare(b.country)).slice(0, 8);
const safe = (url) => /^https?:\/\//i.test(url || '') ? url : '';

const html = `<!-- static-summary:start (generated by scripts/build-static.cjs) -->
          <article class="static-summary">
            <p class="eyebrow">FOOD &amp; AGRICULTURE POLICY · GCC STATES &amp; YEMEN</p>
            <h1>Policy Intelligence</h1>
            <p>Food and agriculture policy measures monitored for Bahrain, Kuwait, Oman, Qatar, Saudi Arabia, the United Arab Emirates and Yemen: ${summary.recordCount.toLocaleString('en-GB')} measures from ${escape(date(first))} to ${escape(date(summary.dataThrough))}.</p>
            <table><caption>Policy measures by country</caption><thead><tr><th scope="col">Country</th><th scope="col">Measures</th></tr></thead><tbody>${countries.map((country) => `<tr><td>${escape(country)}</td><td>${counts[country].toLocaleString('en-GB')}</td></tr>`).join('')}</tbody></table>
            <h2>Latest measures</h2>
            <ul>${latest.map((record) => `<li>${escape(date(record.date))}, ${escape(record.country)}: ${safe(record.source) ? `<a href="${escape(record.source)}" rel="noopener noreferrer">${escape(record.title)}</a>` : escape(record.title)}</li>`).join('')}</ul>
            <p class="static-note">Policy measures are short summaries compiled for monitoring and analysis, not legal texts. Always consult the original source. JavaScript is needed for the interactive dashboard.</p>
          </article>
          <!-- static-summary:end -->`;

const indexPath = path.join(root, 'index.html');
let index = fs.readFileSync(indexPath, 'utf8');
if (!/<!-- static-summary:start[\s\S]*?static-summary:end -->/.test(index)) throw new Error('index.html is missing the static-summary markers.');
index = index.replace(/<!-- static-summary:start[\s\S]*?static-summary:end -->/, html);
const description = `Food and agriculture policy intelligence for the GCC States and Yemen: ${summary.recordCount.toLocaleString('en-GB')} monitored policy measures to ${date(summary.dataThrough)}, with country, trend and food price analysis.`;
index = index.replace(/(<meta name="description" content=")[^"]*(")/, `$1${escape(description)}$2`).replace(/(<meta property="og:description" content=")[^"]*(")/, `$1${escape(description)}$2`);
fs.writeFileSync(indexPath, index, 'utf8');
console.log(`Static summary written: ${summary.recordCount} measures to ${summary.dataThrough}, ${latest.length} latest measures.`);
