#!/usr/bin/env node
'use strict';

// Writes assets/vendor/lucide-icons.js: only the Lucide icons this site uses, plus a small createIcons().
// Icon names are found as quoted kebab-case strings in the source that match a Lucide icon.
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');

const root = path.resolve(__dirname, '..');
const context = {};
context.window = context; context.self = context; context.globalThis = context;
vm.createContext(context);
vm.runInContext(fs.readFileSync(path.join(root, 'assets/vendor/lucide.min.js'), 'utf8'), context);
const all = context.lucide.icons;
const pascal = (name) => name.split('-').map((part) => part.charAt(0).toUpperCase() + part.slice(1)).join('');

const sources = fs.readdirSync(root).filter((file) => /\.(js|html)$/.test(file)).map((file) => fs.readFileSync(path.join(root, file), 'utf8')).join('\n');
const used = [...new Set(sources.match(/["'`]([a-z][a-z0-9]*(?:-[a-z0-9]+)*)["'`]/g) || [])].map((token) => token.slice(1, -1)).filter((name) => all[pascal(name)]).sort();
const icons = Object.fromEntries(used.map((name) => [name, all[pascal(name)][2]]));

const output = `/* Lucide v0.468.0 icon subset (ISC licence, https://lucide.dev). Generated by scripts/build-icons.cjs; do not edit. */
(function () {
  var NS = "http://www.w3.org/2000/svg";
  var icons = ${JSON.stringify(icons)};
  var base = { xmlns: NS, width: 24, height: 24, viewBox: "0 0 24 24", fill: "none", stroke: "currentColor", "stroke-width": 2, "stroke-linecap": "round", "stroke-linejoin": "round" };
  function build(tag, attrs) { var el = document.createElementNS(NS, tag); Object.keys(attrs).forEach(function (key) { el.setAttribute(key, attrs[key]); }); return el; }
  function createIcons(options) {
    var extra = (options && options.attrs) || {};
    document.querySelectorAll("[data-lucide]").forEach(function (el) {
      var name = el.getAttribute("data-lucide"), children = icons[name];
      if (!children) return;
      var svg = build("svg", Object.assign({}, base, extra));
      Array.prototype.forEach.call(el.attributes, function (attr) { if (attr.name !== "data-lucide") svg.setAttribute(attr.name, attr.value); });
      svg.setAttribute("class", ["lucide", "lucide-" + name, el.getAttribute("class") || ""].join(" ").trim());
      children.forEach(function (child) { svg.appendChild(build(child[0], child[1])); });
      el.parentNode.replaceChild(svg, el);
    });
  }
  window.lucide = { icons: icons, createIcons: createIcons };
})();
`;
fs.writeFileSync(path.join(root, 'assets/vendor/lucide-icons.js'), output, 'utf8');
console.log(`Wrote ${used.length} Lucide icons (${Math.round(output.length / 1024)} KB).`);
